from __future__ import annotations

import base64
import io
import json
from functools import lru_cache
from typing import Any

from PIL import Image

from app.core.config import PROJECT_ROOT
from app.ml.segmentation import (
    SEGMENTATION_IMAGE_SIZE,
    build_segmentation_model,
    create_overlay,
)

SEGMENTATION_MODEL_DIRECTORY = PROJECT_ROOT / "backend" / "artifacts" / "segmentation"
SEGMENTATION_SELECTION_PATH = SEGMENTATION_MODEL_DIRECTORY / "selection.json"
SEGMENTATION_RUN_CHECKPOINT = (
    PROJECT_ROOT
    / "backend"
    / "artifacts"
    / "segmentation_isbi2016_run_20261102"
    / "unet.pth"
)


def _segmentation_artifact() -> tuple[Path, str] | None:
    if SEGMENTATION_SELECTION_PATH.is_file():
        with SEGMENTATION_SELECTION_PATH.open(encoding="utf-8") as file:
            selection = json.load(file)
        return (
            SEGMENTATION_MODEL_DIRECTORY / selection["weights"],
            selection["architecture"],
        )
    if SEGMENTATION_RUN_CHECKPOINT.is_file():
        return SEGMENTATION_RUN_CHECKPOINT, "unet"
    return None


def get_lesion_detection_status() -> dict[str, str]:
    artifact = _segmentation_artifact()
    if artifact is None:
        return {
            "status": "pending",
            "reason": (
                "Train the independent ISBI 2016 ISIC Part 1 segmentation model before "
                "requesting pixel-level lesion masks. HAM10000 classification is not "
                "lesion detection."
            ),
        }
    return {
        "status": "available",
        "dataset": "ISBI 2016 ISIC Part 1",
        "reason": (
            f"Pixel masks are generated by the {artifact[1]} model trained on "
            "ISBI 2016 ISIC Part 1."
        ),
    }


@lru_cache(maxsize=1)
def _load_segmentation_model(selection_mtime: int) -> Any:
    import torch

    artifact = _segmentation_artifact()
    if artifact is None:
        raise FileNotFoundError("No trained segmentation checkpoint is available.")
    model_path, model_name = artifact
    if model_path.parent.resolve() not in {
        SEGMENTATION_MODEL_DIRECTORY.resolve(),
        SEGMENTATION_RUN_CHECKPOINT.parent.resolve(),
    }:
        raise ValueError("Segmentation weights must be stored in an approved model directory.")
    model = build_segmentation_model(model_name)
    model.load_state_dict(torch.load(model_path, map_location="cpu", weights_only=True))
    model.eval()
    return model


def predict_lesion_mask(image_bytes: bytes) -> dict[str, object]:
    status = get_lesion_detection_status()
    if status["status"] != "available":
        return status
    import torch
    from torchvision import transforms

    with Image.open(io.BytesIO(image_bytes)) as source:
        image = source.convert("RGB")
        transform = transforms.Compose(
            [transforms.Resize((SEGMENTATION_IMAGE_SIZE, SEGMENTATION_IMAGE_SIZE)), transforms.ToTensor()]
        )
        tensor = transform(image).unsqueeze(0)
        artifact = _segmentation_artifact()
        if artifact is None:
            raise FileNotFoundError("No trained segmentation checkpoint is available.")
        model = _load_segmentation_model(artifact[0].stat().st_mtime_ns)
        with torch.inference_mode():
            mask = (torch.sigmoid(model(tensor))[0, 0] > 0.5).float()
        overlay = create_overlay(image, mask)
        mask_image = Image.fromarray((mask.numpy() * 255).astype("uint8"))
        encoded: dict[str, str] = {}
        for name, rendered in (("mask", mask_image), ("overlay", overlay)):
            buffer = io.BytesIO()
            rendered.save(buffer, format="PNG")
            encoded[name] = base64.b64encode(buffer.getvalue()).decode("ascii")
    return {
        "status": "available",
        "architecture": artifact[1],
        "mask_data_url": f"data:image/png;base64,{encoded['mask']}",
        "overlay_data_url": f"data:image/png;base64,{encoded['overlay']}",
    }
